/** Resolve which product slugs belong to a collection definition. */
export function matchProductSlugs(
  collection: SeoCollection,
  products: { slug: string; tags: string[] }[],
) {
  const set = new Set<string>(collection.productSlugs ?? []);
  if (collection.matchTags?.length) {
    for (const p of products) {
      if (collection.matchTags.some((t) => p.tags.includes(t))) set.add(p.slug);
    }
  }
  return [...set];
}
